USE Sistema_Biblioteca;

-- Vista 1: Información legible y desnormalizada del historial de préstamos
CREATE OR REPLACE VIEW VW_PRESTAMOS_DETALLE AS
SELECT 
    pr.FECHA_P AS FECHA_PRESTAMO,
    CONCAT(est.NOMBRES, ' ', est.APELLIDOS) AS ESTUDIANTE,
    lb.TITULO AS LIBRO,
    CONCAT(fn.NOMBRES, ' ', fn.APELLIDOS) AS FUNCIONARIO_A_CARGO,
    cr.NOMBRE AS CARRERA_ESTUDIANTE
FROM PRESTAMO pr
INNER JOIN ESTUDIANTES est ON pr.RUT_EST = est.RUT_EST
INNER JOIN LIBROS lb ON pr.COD_LIBRO = lb.COD_LIBRO
INNER JOIN FUNCIONARIOS fn ON pr.RUT_FUNC = fn.RUT_FUNC
INNER JOIN CARRERAS cr ON est.ID_CARRERA = cr.ID_CARRERA;

-- Vista 2: Balance de inventario bibliográfico agrupado por biblioteca física
CREATE OR REPLACE VIEW VW_LIBROS_POR_BIBLIOTECA AS
SELECT 
    bib.ID_BIBLIO,
    bib.BIBLIOTECA AS SEDE_BIBLIOTECA,
    COUNT(lb.COD_LIBRO) AS TOTAL_VOLUMENES
FROM BIBLIOTECA bib
LEFT JOIN LIBROS lb ON bib.ID_BIBLIO = lb.ID_BIBLIO
GROUP BY bib.ID_BIBLIO, bib.BIBLIOTECA;