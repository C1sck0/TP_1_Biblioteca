DROP DATABASE IF EXISTS Sistema_Biblioteca;
CREATE DATABASE Sistema_Biblioteca CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE Sistema_Biblioteca;

---------------------------------------------------------------

CREATE TABLE CIUDAD (
    ID_CIUDAD INT NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    CONSTRAINT PK_CIUDAD PRIMARY KEY (ID_CIUDAD)
);

CREATE TABLE CAMPUS (
    ID_CAMPUS INT NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    ID_CIUDAD INT NOT NULL,
    CONSTRAINT PK_CAMPUS PRIMARY KEY (ID_CAMPUS),
    CONSTRAINT FK_CAMPUS_CIUDAD FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

CREATE TABLE CARRERAS (
    ID_CARRERA INT NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    CONSTRAINT PK_CARRERAS PRIMARY KEY (ID_CARRERA),
    CONSTRAINT FK_CARRERAS_CAMPUS FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

---------------------------------------------------------------

CREATE TABLE ESTUDIANTES (
    RUT_EST VARCHAR(20) NOT NULL,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD INT NOT NULL,
    FONO VARCHAR(30) NULL,
    DIRECCION VARCHAR(150) NULL,
    ID_CARRERA INT NOT NULL,
    CONSTRAINT PK_ESTUDIANTES PRIMARY KEY (RUT_EST),
    CONSTRAINT FK_ESTUDIANTES_CARRERA FOREIGN KEY (ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA)
);

CREATE TABLE FUNCIONARIOS (
    RUT_FUNC VARCHAR(20) NOT NULL,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    EDAD INT NOT NULL,
    DIRECCION VARCHAR(150) NULL,
    SALUD VARCHAR(50) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    CONSTRAINT PK_FUNCIONARIOS PRIMARY KEY (RUT_FUNC),
    CONSTRAINT FK_FUNCIONARIOS_CAMPUS FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

----------------------------------------------------------------

CREATE TABLE AUTORES (
    RUT_AUTOR VARCHAR(20) NOT NULL,
    NOMBRES VARCHAR(100) NOT NULL,
    APELLIDOS VARCHAR(100) NOT NULL,
    CONSTRAINT PK_AUTORES PRIMARY KEY (RUT_AUTOR)
);

CREATE TABLE EDITORIALES (
    ID_EDIT INT NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    PAIS VARCHAR(80) NOT NULL,
    CONSTRAINT PK_EDITORIALES PRIMARY KEY (ID_EDIT)
);

CREATE TABLE TIPO (
    ID_TIPO INT NOT NULL,
    TIPO_P VARCHAR(80) NOT NULL,
    CONSTRAINT PK_TIPO PRIMARY KEY (ID_TIPO)
);

CREATE TABLE BIBLIOTECA (
    ID_BIBLIO INT NOT NULL,
    BIBLIOTECA VARCHAR(100) NOT NULL,
    CONSTRAINT PK_BIBLIOTECA PRIMARY KEY (ID_BIBLIO)
);

CREATE TABLE LIBROS (
    COD_LIBRO INT NOT NULL,
    TITULO VARCHAR(200) NOT NULL,
    ANIO INT NOT NULL,
    ID_BIBLIO INT NOT NULL,
    ID_TIPO INT NOT NULL,
    RUT_AUTOR VARCHAR(20) NOT NULL,
    ID_EDIT INT NOT NULL,
    CONSTRAINT PK_LIBROS PRIMARY KEY (COD_LIBRO),
    CONSTRAINT FK_LIBROS_BIBLIO FOREIGN KEY (ID_BIBLIO) REFERENCES BIBLIOTECA(ID_BIBLIO),
    CONSTRAINT FK_LIBROS_TIPO FOREIGN KEY (ID_TIPO) REFERENCES TIPO(ID_TIPO),
    CONSTRAINT FK_LIBROS_AUTOR FOREIGN KEY (RUT_AUTOR) REFERENCES AUTORES(RUT_AUTOR),
    CONSTRAINT FK_LIBROS_EDIT FOREIGN KEY (ID_EDIT) REFERENCES EDITORIALES(ID_EDIT)
);

